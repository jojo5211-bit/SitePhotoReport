【快速上手】
1. 新增工程：首頁點「新增工程」，輸入工程名稱即可建立。
2. 拍照／匯入：進入欄位後點右下角「拍照／匯入」，可直接拍照放入該欄位；拍攝照片會同步保存到手機內建相簿，或從相簿批次選取。
3. 分類照片：
   • 快速分類（滑動式）：工程總覽點「拍照或快速分類」，逐張點選目標欄位。
