   • 無 API 時：自動改用檔名關鍵字比對產生建議。
4. 調整順序：進入欄位後點右上角排序圖示，可選手動、拍攝時間早到晚／晚到早、檔名遞增／遞減；拖曳排序會切回手動順序。
5. 照片編輯：點照片進詳情，可旋轉、馬賽克遮蔽、移動欄位、填寫說明／位置。
