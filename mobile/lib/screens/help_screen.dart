【資料格式】
• 與桌面版完全相容的 .sprj 格式（SQLite + 照片檔）。
• 手機版建立的工程可直接用桌面版開啟，反之亦然。
• 原始照片永不修改；旋轉／馬賽克／編號都是非破壞式疊加。

【AI 分類設定】
選單「設定」→ 新增 API 設定，填入 OpenAI 相容的視覺 API（如 Gemini、OpenRouter）。
