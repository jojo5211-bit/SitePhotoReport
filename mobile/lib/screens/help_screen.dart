6. 編號：選單「一鍵全部編號」為所有欄位各自從 1 開始編號；也可在單一欄位編號。進入欄位後，右上角可取消目前欄位編號；取消不會刪除照片或改變順序。
   • 編號會依設定顯示位置、顏色、大小及透明底色，每張照片只顯示一個編號。
7. 未分類照片：會依拍攝日期排序，跨日期顯示日期分隔線；沒有拍攝日期的照片排在最後。
8. 匯出報告：可選自動排版、每頁6張（2×3）、4張、2張或1張；另可選黑白省墨、清爽藍綠、暖棕工程三種模板。自動模式會讓直式照片最多4張、橫式照片最多2張，並自動縮放不變形。另可開關照片下方的「#1」編號文字。
